static int s5kgw1_init_ctrls(struct s5kgw1 *s5kgw1)
{
	struct i2c_client *client = v4l2_get_subdevdata(&s5kgw1->sd);
	struct v4l2_ctrl_handler *handler = &s5kgw1->ctrl_handler;
	struct v4l2_fwnode_device_properties props;
	const struct s5kgw1_mode *mode = s5kgw1->cur_mode;
	u64 pixel_rate;
	u32 h_blank, v_blank, exposure_max;
	int ret;

	ret = v4l2_ctrl_handler_init(handler, 7);
	if (ret)
		return ret;

	s5kgw1->link_freq = v4l2_ctrl_new_int_menu(handler, NULL, V4L2_CID_LINK_FREQ,
						  ARRAY_SIZE(link_freq_items) - 1, 0, link_freq_items);
	if (s5kgw1->link_freq)
		s5kgw1->link_freq->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	pixel_rate = mode->link_freq * 2 * mode->lane_count / mode->depth;
	s5kgw1->pixel_rate = v4l2_ctrl_new_std(handler, NULL, V4L2_CID_PIXEL_RATE,
					     0, pixel_rate, 1, pixel_rate);

	h_blank = mode->hts - mode->width;
	s5kgw1->hblank = v4l2_ctrl_new_std(handler, NULL, V4L2_CID_HBLANK,
					   h_blank, h_blank, 1, h_blank);
	if (s5kgw1->hblank)
		s5kgw1->hblank->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	v_blank = mode->vts - mode->height;
	s5kgw1->vblank = v4l2_ctrl_new_std(handler, &s5kgw1_ctrl_ops,
					   V4L2_CID_VBLANK, v_blank,
					   0xffff - mode->height, 1, v_blank);

	exposure_max = mode->vts - 3;
	s5kgw1->exposure = v4l2_ctrl_new_std(handler, &s5kgw1_ctrl_ops,
					     V4L2_CID_EXPOSURE, 1,
					     exposure_max, 1, exposure_max / 2);

	v4l2_ctrl_new_std(handler, &s5kgw1_ctrl_ops, V4L2_CID_ANALOGUE_GAIN,
			  32, 512, 1, 128);

	v4l2_ctrl_new_std_menu_items(handler, &s5kgw1_ctrl_ops,
				     V4L2_CID_TEST_PATTERN,
				     ARRAY_SIZE(s5kgw1_test_pattern_menu) - 1,
				     0, 0, s5kgw1_test_pattern_menu);

	if (handler->error) {
		ret = handler->error;
		goto err_free_handler;
	}

	ret = v4l2_fwnode_device_parse(&client->dev, &props);
	if (ret)
		goto err_free_handler;

	ret = v4l2_ctrl_new_fwnode_properties(handler, &s5kgw1_ctrl_ops, &props);
	if (ret)
		goto err_free_handler;

	s5kgw1->sd.ctrl_handler = handler;
	return 0;

err_free_handler:
	dev_err(&client->dev, "Failed to init controls: %d\n", ret);
	v4l2_ctrl_handler_free(handler);
	return ret;
}

static int s5kgw1_check_sensor_id(struct s5kgw1 *s5kgw1)
{
	struct i2c_client *client = v4l2_get_subdevdata(&s5kgw1->sd);
	u32 id = 0;
	int ret;

	ret = s5kgw1_read(s5kgw1, 0x0000, 2, &id);
	if (ret)
		return ret;

	if (id != 0x0971) {
		dev_err(&client->dev, "Chip ID mismatch: expected 0x0971, got 0x%04x\n", id);
		return -ENODEV;
	}

	dev_info(&client->dev, "Detected Samsung S5KGW1 sensor (ID 0x%04x)\n", id);
	return 0;
}

static int s5kgw1_parse_of(struct s5kgw1 *s5kgw1)
{
	struct v4l2_fwnode_endpoint vep = { { 0 } };
	struct i2c_client *client = v4l2_get_subdevdata(&s5kgw1->sd);
	struct device *dev = &client->dev;
	struct fwnode_handle *endpoint;
	int ret;

	endpoint = fwnode_graph_get_next_endpoint(dev_fwnode(dev), NULL);
	if (!endpoint) {
		dev_err(dev, "Failed to get endpoint\n");
		return -EINVAL;
	}

	ret = v4l2_fwnode_endpoint_parse(endpoint, &vep);
	fwnode_handle_put(endpoint);
	if (ret) {
		dev_err(dev, "Failed to parse endpoint: %d\n", ret);
		return ret;
	}

	s5kgw1->cur_mode = &s5kgw1_modes[0];
	return 0;
}


/*
 * libcamera keeps the lens sub-device open for as long as the camera manager
 * runs, so the focus actuator cannot rely on open()/close() for its power.
 * Make it a runtime-PM supplier of the sensor instead: it is then powered
 * exactly while the sensor is, and restores its position on resume.
 */
static struct device_link *s5kgw1_link_lens(struct device *dev)
{
	struct fwnode_handle *lens;
	struct device_link *link;
	struct device *lens_dev;

	lens = fwnode_find_reference(dev_fwnode(dev), "lens-focus", 0);
	if (IS_ERR(lens))
		return NULL;
	lens_dev = bus_find_device_by_fwnode(&i2c_bus_type, lens);
	fwnode_handle_put(lens);
	if (!lens_dev)
		return NULL;
	link = device_link_add(dev, lens_dev,
			       DL_FLAG_STATELESS | DL_FLAG_PM_RUNTIME);
	put_device(lens_dev);
	if (!link)
		dev_warn(dev, "failed to link the lens actuator\n");
	return link;
}

static int s5kgw1_probe(struct i2c_client *client)
{
	struct device *dev = &client->dev;
	struct s5kgw1 *s5kgw1;
	struct v4l2_subdev *sd;
	int ret;

	s5kgw1 = devm_kzalloc(dev, sizeof(*s5kgw1), GFP_KERNEL);
	if (!s5kgw1)
		return -ENOMEM;

	s5kgw1->xvclk = devm_clk_get(dev, "xvclk");
	if (IS_ERR(s5kgw1->xvclk))
		return dev_err_probe(dev, PTR_ERR(s5kgw1->xvclk), "Failed to get xvclk\n");

	s5kgw1->reset_gpio = devm_gpiod_get(dev, "reset", GPIOD_OUT_LOW);
	if (IS_ERR(s5kgw1->reset_gpio))
		return dev_err_probe(dev, PTR_ERR(s5kgw1->reset_gpio), "Failed to get reset gpio\n");

	v4l2_i2c_subdev_init(&s5kgw1->sd, client, &s5kgw1_subdev_ops);
	s5kgw1->sd.internal_ops = &s5kgw1_internal_ops;

	for (unsigned int i = 0; i < ARRAY_SIZE(s5kgw1_supply_names); i++)
		s5kgw1->supplies[i].supply = s5kgw1_supply_names[i];

	ret = devm_regulator_bulk_get(&client->dev, ARRAY_SIZE(s5kgw1_supply_names), s5kgw1->supplies);
	if (ret)
		return dev_err_probe(dev, ret, "Failed to get regulators\n");

	ret = s5kgw1_parse_of(s5kgw1);
	if (ret)
		return ret;

	ret = s5kgw1_init_ctrls(s5kgw1);
	if (ret)
		return ret;

	sd = &s5kgw1->sd;
	sd->flags |= V4L2_SUBDEV_FL_HAS_DEVNODE;
	s5kgw1->pad.flags = MEDIA_PAD_FL_SOURCE;
	sd->entity.function = MEDIA_ENT_F_CAM_SENSOR;
	ret = media_entity_pads_init(&sd->entity, 1, &s5kgw1->pad);
	if (ret < 0)
		goto err_free_handler;

	sd->state_lock = s5kgw1->ctrl_handler.lock;
	ret = v4l2_subdev_init_finalize(sd);
	if (ret < 0) {
		dev_err(&client->dev, "Subdev initialization error %d\n", ret);
		goto err_clean_entity;
	}

	ret = s5kgw1_power_on(dev);
	if (ret)
		goto err_clean_entity;

	pm_runtime_set_active(dev);
	pm_runtime_get_noresume(dev);
	pm_runtime_enable(dev);

	ret = s5kgw1_check_sensor_id(s5kgw1);
	if (ret)
		goto err_power_off;

	pm_runtime_set_autosuspend_delay(dev, 1000);
	pm_runtime_use_autosuspend(dev);

	s5kgw1->lens_link = s5kgw1_link_lens(dev);

	ret = v4l2_async_register_subdev_sensor(sd);
	if (ret) {
		dev_err(dev, "v4l2 async register subdev failed\n");
		goto err_power_off;
	}

	pm_runtime_mark_last_busy(dev);
	pm_runtime_put_autosuspend(dev);

	return 0;

err_power_off:
	if (s5kgw1->lens_link)
		device_link_del(s5kgw1->lens_link);
	pm_runtime_disable(dev);
	pm_runtime_put_noidle(dev);
	s5kgw1_power_off(dev);
err_clean_entity:
	media_entity_cleanup(&sd->entity);
err_free_handler:
	v4l2_ctrl_handler_free(&s5kgw1->ctrl_handler);
	return ret;
}

static void s5kgw1_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct s5kgw1 *s5kgw1 = to_s5kgw1_subdev(sd);

	v4l2_async_unregister_subdev(sd);
	media_entity_cleanup(&sd->entity);
	v4l2_ctrl_handler_free(&s5kgw1->ctrl_handler);

	pm_runtime_disable(&client->dev);
	if (!pm_runtime_status_suspended(&client->dev))
		s5kgw1_power_off(&client->dev);
	pm_runtime_set_suspended(&client->dev);
	if (s5kgw1->lens_link)
		device_link_del(s5kgw1->lens_link);
}

static const struct dev_pm_ops s5kgw1_pm_ops = {
	SET_RUNTIME_PM_OPS(s5kgw1_power_off, s5kgw1_power_on, NULL)
};

static const struct of_device_id s5kgw1_of_match[] = {
	{ .compatible = "samsung,s5kgw1" },
	{ /* sentinel */ }
};
MODULE_DEVICE_TABLE(of, s5kgw1_of_match);

static struct i2c_driver s5kgw1_i2c_driver = {
	.driver = {
		.of_match_table = s5kgw1_of_match,
		.pm = &s5kgw1_pm_ops,
		.name = "s5kgw1",
	},
	.probe  = s5kgw1_probe,
	.remove = s5kgw1_remove,
};

module_i2c_driver(s5kgw1_i2c_driver);

