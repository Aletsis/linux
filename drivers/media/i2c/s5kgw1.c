static int s5kgw1_power_on(struct device *dev)
{
	struct v4l2_subdev *sd = dev_get_drvdata(dev);
	struct s5kgw1 *s5kgw1 = to_s5kgw1_subdev(sd);
	struct i2c_client *client = v4l2_get_subdevdata(sd);
	int ret;

	if (client->dev.parent) {
		ret = pm_runtime_get_sync(client->dev.parent);
		if (ret < 0) {
			pm_runtime_put_noidle(client->dev.parent);
			return ret;
		}
	}

	gpiod_set_value_cansleep(s5kgw1->reset_gpio, 0);
	usleep_range(1000, 2000);

	ret = regulator_bulk_enable(ARRAY_SIZE(s5kgw1_supply_names), s5kgw1->supplies);
	if (ret) {
		dev_err(dev, "failed to enable regulators\n");
		if (client->dev.parent)
			pm_runtime_put(client->dev.parent);
		return ret;
	}
	usleep_range(1000, 2000);

	ret = clk_prepare_enable(s5kgw1->xvclk);
	if (ret) {
		dev_err(dev, "Failed to enable xvclk\n");
		goto disable_regulator;
	}
	usleep_range(10000, 11000);

	gpiod_set_value_cansleep(s5kgw1->reset_gpio, 1);
	usleep_range(18000, 20000);

	{
		const struct s5kgw1_reg_list init_list = {
			.num_of_regs = ARRAY_SIZE(s5kgw1_oem_init_regs),
			.regs = s5kgw1_oem_init_regs,
		};

		dev_info(dev, "Writing init regs (%u regs)...\n", init_list.num_of_regs);
		ret = s5kgw1_write_reg_list(s5kgw1, &init_list);
		if (ret) {
			dev_err(dev, "Failed to write init register list: %d\n", ret);
			goto disable_regulator;
		}
	}

	return 0;

disable_regulator:
	regulator_bulk_disable(ARRAY_SIZE(s5kgw1_supply_names), s5kgw1->supplies);
	if (client->dev.parent)
		pm_runtime_put(client->dev.parent);
	return ret;
}

static int s5kgw1_power_off(struct device *dev)
{
	struct v4l2_subdev *sd = dev_get_drvdata(dev);
	struct s5kgw1 *s5kgw1 = to_s5kgw1_subdev(sd);
	struct i2c_client *client = v4l2_get_subdevdata(sd);

	s5kgw1->mode_programmed = false;

	gpiod_set_value_cansleep(s5kgw1->reset_gpio, 0);
	usleep_range(1000, 2000);

	clk_disable_unprepare(s5kgw1->xvclk);
	usleep_range(1000, 2000);

	regulator_bulk_disable(ARRAY_SIZE(s5kgw1_supply_names), s5kgw1->supplies);

	if (client->dev.parent)
		pm_runtime_put(client->dev.parent);

	return 0;
}

static int s5kgw1_start_stream(struct s5kgw1 *s5kgw1)
{
	int ret;

	if (!s5kgw1->mode_programmed) {
		dev_info(s5kgw1->sd.dev, "Writing mode %ux%u (%u regs)...\n",
			 s5kgw1->cur_mode->width, s5kgw1->cur_mode->height,
			 s5kgw1->cur_mode->reg_list.num_of_regs);
		ret = s5kgw1_write_reg_list(s5kgw1, &s5kgw1->cur_mode->reg_list);
		if (ret) {
			dev_err(s5kgw1->sd.dev, "Failed to write mode register list: %d\n", ret);
			return ret;
		}
		s5kgw1->mode_programmed = true;
	}

	ret = __v4l2_ctrl_handler_setup(&s5kgw1->ctrl_handler);
	if (ret)
		return ret;

	/* Start streaming immediately: OEM start sequence */
	dev_info(s5kgw1->sd.dev, "Starting stream (fast start)...\n");
	ret = s5kgw1_write(s5kgw1, 0x0100, 1, 0x01);
	if (ret) {
		dev_err(s5kgw1->sd.dev, "Failed to start streaming: %d\n", ret);
		return ret;
	}

	{
		u32 r100 = 0, r104 = 0, r114 = 0, r118 = 0;
		s5kgw1_read(s5kgw1, 0x0100, 1, &r100);
		s5kgw1_read(s5kgw1, 0x0104, 1, &r104);
		s5kgw1_read(s5kgw1, 0x0114, 2, &r114);
		s5kgw1_read(s5kgw1, 0x0118, 2, &r118);
		dev_info(s5kgw1->sd.dev, "Streaming status: 0x0100=0x%02x 0x0104=0x%02x 0x0114=0x%04x 0x0118=0x%04x\n",
			 r100, r104, r114, r118);
	}

	return 0;
}

static int s5kgw1_stop_stream(struct s5kgw1 *s5kgw1)
{
	u32 fc = 0, fstatus = 0;
	s5kgw1_read(s5kgw1, 0x0002, 2, &fc);
	s5kgw1_read(s5kgw1, 0x0118, 2, &fstatus);
	dev_info(s5kgw1->sd.dev, "Stopping stream: frames_sent=0x%04x (dec %u) fifo_status=0x%04x\n",
		 fc, fc, fstatus);
	s5kgw1_write(s5kgw1, 0x0100, 1, 0x00);
	s5kgw1_write(s5kgw1, 0x6028, 2, 0x4000);
	s5kgw1_write(s5kgw1, 0x6218, 2, 0xf150);
	return 0;
}

static int s5kgw1_s_stream(struct v4l2_subdev *sd, int on)
{
	struct i2c_client *client = v4l2_get_subdevdata(sd);
	struct s5kgw1 *s5kgw1 = to_s5kgw1_subdev(sd);
	struct v4l2_subdev_state *state;
	int ret = 0;

	dev_info(&client->dev, "s_stream: on=%d\n", on);

	state = v4l2_subdev_lock_and_get_active_state(sd);

	if (on) {
		ret = pm_runtime_resume_and_get(&client->dev);
		if (ret < 0)
			goto unlock_and_return;

		ret = s5kgw1_start_stream(s5kgw1);
		if (ret) {
			dev_err(&client->dev, "Failed to start streaming\n");
			pm_runtime_put_sync(&client->dev);
			goto unlock_and_return;
		}
	} else {
		s5kgw1_stop_stream(s5kgw1);
		pm_runtime_mark_last_busy(&client->dev);
		pm_runtime_put_autosuspend(&client->dev);
	}

unlock_and_return:
	v4l2_subdev_unlock_state(state);
	return ret;
}

static int s5kgw1_set_fmt(struct v4l2_subdev *sd,
			  struct v4l2_subdev_state *state,
			  struct v4l2_subdev_format *fmt)
{
	struct s5kgw1 *s5kgw1 = to_s5kgw1_subdev(sd);
	const struct s5kgw1_mode *mode;
	struct v4l2_mbus_framefmt *format;
	u64 pixel_rate;
	u32 v_blank;
	u32 h_blank;
	unsigned int i;

	mode = v4l2_find_nearest_size(s5kgw1_modes, ARRAY_SIZE(s5kgw1_modes),
				      width, height, fmt->format.width,
				      fmt->format.height);

	fmt->format.code = mode->mbus_code;
	fmt->format.width = mode->width;
	fmt->format.height = mode->height;
	fmt->format.field = V4L2_FIELD_NONE;

	format = v4l2_subdev_state_get_format(state, fmt->pad);
	*format = fmt->format;

	if (fmt->which == V4L2_SUBDEV_FORMAT_ACTIVE) {
		bool mode_changed = (s5kgw1->cur_mode != mode);

		s5kgw1->cur_mode = mode;
		if (mode_changed && s5kgw1->mode_programmed)
			s5kgw1_write_reg_list(s5kgw1, &s5kgw1->cur_mode->reg_list);

		pixel_rate = mode->link_freq * 2 * mode->lane_count / mode->depth;
		__v4l2_ctrl_s_ctrl_int64(s5kgw1->pixel_rate, pixel_rate);

		for (i = 0; i < ARRAY_SIZE(link_freq_items); i++) {
			if (link_freq_items[i] == mode->link_freq) {
				__v4l2_ctrl_s_ctrl(s5kgw1->link_freq, i);
				break;
			}
		}

		v_blank = mode->vts - mode->height;
		__v4l2_ctrl_modify_range(s5kgw1->vblank, v_blank,
					 0xffff - mode->height, 1, v_blank);
		__v4l2_ctrl_s_ctrl(s5kgw1->vblank, v_blank);

		h_blank = mode->hts - mode->width;
		__v4l2_ctrl_modify_range(s5kgw1->hblank, h_blank,
					 h_blank, 1, h_blank);
	}

	return 0;
}

static int s5kgw1_get_selection(struct v4l2_subdev *sd,
				struct v4l2_subdev_state *sd_state,
				struct v4l2_subdev_selection *sel)
{
	struct v4l2_mbus_framefmt *format;

	switch (sel->target) {
	case V4L2_SEL_TGT_CROP:
	case V4L2_SEL_TGT_CROP_DEFAULT:
	case V4L2_SEL_TGT_CROP_BOUNDS:
		format = v4l2_subdev_state_get_format(sd_state, sel->pad);
		sel->r.top = 0;
		sel->r.left = 0;
		sel->r.width = format->width;
		sel->r.height = format->height;
		return 0;
	case V4L2_SEL_TGT_NATIVE_SIZE:
		sel->r.top = 0;
		sel->r.left = 0;
		sel->r.width = 9280;
		sel->r.height = 6944;
		return 0;
	}

	return -EINVAL;
}

static int s5kgw1_enum_mbus_code(struct v4l2_subdev *sd,
				 struct v4l2_subdev_state *sd_state,
				 struct v4l2_subdev_mbus_code_enum *code)
{
	if (code->index >= 1)
		return -EINVAL;

	code->code = MEDIA_BUS_FMT_SGRBG10_1X10;
	return 0;
}

static int s5kgw1_enum_frame_sizes(struct v4l2_subdev *sd,
				  struct v4l2_subdev_state *sd_state,
				  struct v4l2_subdev_frame_size_enum *fse)
{
	if (fse->index >= ARRAY_SIZE(s5kgw1_modes))
		return -EINVAL;

	if (fse->code != MEDIA_BUS_FMT_SGRBG10_1X10)
		return -EINVAL;

	fse->min_width = s5kgw1_modes[fse->index].width;
	fse->max_width = s5kgw1_modes[fse->index].width;
	fse->min_height = s5kgw1_modes[fse->index].height;
	fse->max_height = s5kgw1_modes[fse->index].height;

	return 0;
}

static int s5kgw1_init_state(struct v4l2_subdev *sd,
			     struct v4l2_subdev_state *sd_state)
{
	struct v4l2_subdev_format fmt = {
		.which = V4L2_SUBDEV_FORMAT_TRY,
		.pad = 0,
		.format = {
			.code = MEDIA_BUS_FMT_SGRBG10_1X10,
			.width = s5kgw1_modes[0].width,
			.height = s5kgw1_modes[0].height,
		},
	};

	return s5kgw1_set_fmt(sd, sd_state, &fmt);
}

